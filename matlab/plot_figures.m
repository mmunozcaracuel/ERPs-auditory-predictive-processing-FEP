function validate_pinv(pinvData, longData, group)
% Verificar definicion, dimensiones y orden de sujetos antes de representar.
pinvField = ['ERPtotal_' group '_PINV_preS4BL'];
longField = ['ERPtotal_' group '_CNV_PINV'];
fields = {pinvField, 'subject_names', 'timePinvS4', ...
    'pinvBaselineMsRelativeToS4'};
if ~all(isfield(pinvData, fields)) || ~isfield(longData, 'subject_names')
    error('Faltan datos o metadatos de PINV para %s.', group);
end
if ~isequal(size(pinvData.(pinvField)), size(longData.(longField))) || ...
        ~isequal(string(pinvData.subject_names(:)), string(longData.subject_names(:)))
    error('PINV y las epocas largas no coinciden en dimensiones o sujetos: %s.', group);
end
expectedTime = -1000 + (0:(size(pinvData.(pinvField), 2) - 1));
if ~isequal(pinvData.timePinvS4(:)', expectedTime) || ...
        ~isequal(pinvData.pinvBaselineMsRelativeToS4(:)', [-100 0])
    error('Eje temporal o linea base de PINV inesperados: %s.', group);
end
end

function plot_mean_sem(data, color, lineStyle, time)
% Cada fila corresponde a un participante; sombreado = media +/- SEM.
average = mean(data, 1);
sem = std(data, 0, 1) ./ sqrt(size(data, 1));
shadeColor = color + 0.6 .* (1 - color);
fill([time(:)' fliplr(time(:)')], ...
    [average - sem fliplr(average + sem)], shadeColor, ...
    'EdgeColor', 'none', 'FaceAlpha', 0.5);
hold on;
plot(time, average, 'Color', color, 'LineStyle', lineStyle, 'LineWidth', 3);
end
