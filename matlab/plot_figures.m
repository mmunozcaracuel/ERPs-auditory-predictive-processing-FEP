            'Color', 'w', ...
            'XColor', 'k', ...
            'YColor', 'k', ...
            'Box', 'off');

        % Desactivar la barra flotante y las interacciones de los ejes

        disableDefaultInteractivity(currentAxes);
        emptyAxesToolbar = axtoolbar(currentAxes, {});
        emptyAxesToolbar.Visible = 'off';

        % Añadir líneas de eventos sin las etiquetas S1, S2, S3 o S4

        for eventIndex = 1:numel(eventTimes)

            eventLine = xline( ...
                eventTimes(eventIndex), ...
                '--k', ...
                'LineWidth', 2);

            eventLine.HandleVisibility = 'off';
        end

        % Ajustar límites, posiciones reales y etiquetas visibles

        switch axisMode

            case 'CNV'

                xlim([-100 900]);
                xticks([-100 0 300 600 900]);
                xticklabels({'-100', '0', '300', '600', '900'});

            case 'MMN'

                xlim([-50 300]);
                xticks([-50 0 50 100 150 200 250 300]);

            case 'PINV'

                xlim([-100 1000]);
                xticks([-100 0 200 400 600 800 1000]);

            case 'FULL_SEQUENCE'

                xlim([-100 1898]);
                xticks([ ...
                    -100 0 300 600 900 ...
                    1100 1300 1500 1700 1898]);
                xticklabels({ ...
                    '-100', '0', '300', '600', '900', ...
                    '1100', '1300', '1500', '1700', '1900'});
                xlabel('Nominal time from S1 (ms)', 'Color', 'k');

            otherwise

                error('Modo de eje desconocido: %s', axisMode);
        end

        box off

        % Completar la actualización gráfica antes de guardar

        drawnow

        pngFile = fullfile( ...
            channelPngPath, ...
            [outputStem '.png']);

        figFile = fullfile( ...
            channelFigPath, ...
            [outputStem '.fig']);

        % Exportar el PNG mientras la figura permanece oculta

        exportgraphics(currentFigure, pngFile, 'Resolution', 300);

        % Guardar el FIG con visibilidad activa para que se abra
        % normalmente al hacer doble clic en MATLAB

        currentFigure.Visible = 'on';
        drawnow
        savefig(currentFigure, figFile);
        close(currentFigure);
    end
end

