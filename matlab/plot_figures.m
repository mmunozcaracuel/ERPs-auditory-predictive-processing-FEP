
% REPRESENTACION DE ERP: MEDIA Y ERROR ESTANDAR ENTRE PARTICIPANTES
% Procesamiento principal: HPF 0.05 Hz, LPF 30 Hz y rechazo a +/-100 uV
% Componentes de interés: MMN, CNV y PINV
% PINV principal: DEV-STD con linea base de -100 a 0 ms respecto a S4

clearvars
close all
clc

% Cambiar a true solo para regenerar las salidas de este script
% Las matrices ERP y los resultados estadisticos no se modifican

overwriteExistingFigures = false;

% Rutas

scriptPath = fileparts(mfilename('fullpath'));
projectPath = fileparts(fileparts(scriptPath));
dataPath = fullfile(projectPath, 'EEG');

figurePath = fullfile( ...
    dataPath, ...
    'Figuras_PINV_principal_preS4BL');
pngFigurePath = fullfile(figurePath, 'PNG');
figFigurePath = fullfile(figurePath, 'FIG');
plotDataPath = fullfile( ...
    dataPath, ...
    'Plot_data_PINV_principal_preS4BL');

if isfolder(figurePath)
    existingFigureFiles = dir(fullfile(figurePath, '**', '*'));
    existingFigureFiles = existingFigureFiles(~[existingFigureFiles.isdir]);

    if ~isempty(existingFigureFiles) && ...
            ~overwriteExistingFigures
        error(['La carpeta de figuras ya contiene ' ...
            'archivos y no se sobrescribira: %s'], figurePath);
    end
end

if isfolder(plotDataPath)
    existingPlotDataFiles = dir(fullfile(plotDataPath, '*.mat'));

    if ~isempty(existingPlotDataFiles) && ...
            ~overwriteExistingFigures
        error(['La carpeta de matrices para figuras ya contiene ' ...
            'archivos y no se sobrescribira: %s'], plotDataPath);
    end
end

% Matrices definitivas generadas por el procesamiento nuevo

conMmnFile = fullfile( ...
    dataPath, ...
    'ERPtotal_CON_MMN_0p05Hz.mat');

pepMmnFile = fullfile( ...
    dataPath, ...
    'ERPtotal_PEP_MMN_0p05Hz.mat');

conCnvPinvFile = fullfile( ...
    dataPath, ...
    'ERPtotal_CON_CNV_PINV_0p05Hz.mat');

pepCnvPinvFile = fullfile( ...
    dataPath, ...
    'ERPtotal_PEP_CNV_PINV_0p05Hz.mat');

conPinvFile = fullfile(dataPath, 'ERPtotal_CON_PINV_preS4BL_0p05Hz.mat');
pepPinvFile = fullfile(dataPath, 'ERPtotal_PEP_PINV_preS4BL_0p05Hz.mat');

requiredFiles = { ...
    conMmnFile; ...
    pepMmnFile; ...
    conCnvPinvFile; ...
    pepCnvPinvFile; ...
    conPinvFile; ...
    pepPinvFile};

for fileIndex = 1:numel(requiredFiles)
    if ~isfile(requiredFiles{fileIndex})
        error(['No se encuentra el archivo: %s. Para generar las matrices ' ...
            'PINV pre-S4, ejecute CONFIGURACION DE RUTAS y el apartado 8 ' ...
            'de preprocessing_reference.m.'], requiredFiles{fileIndex});
    end
end

% Cargar los datos sin mezclar los espacios de nombres

CON_MMN_DATA = load(conMmnFile);
PEP_MMN_DATA = load(pepMmnFile);
CON_CNV_PINV_DATA = load(conCnvPinvFile);
PEP_CNV_PINV_DATA = load(pepCnvPinvFile);

% Comprobar las variables necesarias

if ~isfield(CON_MMN_DATA, 'ERPtotal_CON_MMN')
    error('No existe ERPtotal_CON_MMN en %s.', conMmnFile);
end

if ~isfield(PEP_MMN_DATA, 'ERPtotal_PEP_MMN')
    error('No existe ERPtotal_PEP_MMN en %s.', pepMmnFile);
end

if ~isfield(CON_CNV_PINV_DATA, 'ERPtotal_CON_CNV_PINV')
    error('No existe ERPtotal_CON_CNV_PINV en %s.', conCnvPinvFile);
end

if ~isfield(PEP_CNV_PINV_DATA, 'ERPtotal_PEP_CNV_PINV')
    error('No existe ERPtotal_PEP_CNV_PINV en %s.', pepCnvPinvFile);
end

ERP_CON_MMN = CON_MMN_DATA.ERPtotal_CON_MMN;
ERP_PEP_MMN = PEP_MMN_DATA.ERPtotal_PEP_MMN;

ERP_CON_CNV_PINV = ...
    CON_CNV_PINV_DATA.ERPtotal_CON_CNV_PINV;

ERP_PEP_CNV_PINV = ...
    PEP_CNV_PINV_DATA.ERPtotal_PEP_CNV_PINV;

% Cargar la PINV principal ya corregida en preprocessing_reference.m.
% No se aplica una segunda correccion de linea base en este script.
CON_PINV_DATA = load(conPinvFile);
PEP_PINV_DATA = load(pepPinvFile);
validate_pinv(CON_PINV_DATA, CON_CNV_PINV_DATA, 'CON');
validate_pinv(PEP_PINV_DATA, PEP_CNV_PINV_DATA, 'PEP');
ERP_CON_PINV = CON_PINV_DATA.ERPtotal_CON_PINV_preS4BL;
ERP_PEP_PINV = PEP_PINV_DATA.ERPtotal_PEP_PINV_preS4BL;
pinvBaselineMsRelativeToS4 = CON_PINV_DATA.pinvBaselineMsRelativeToS4;

% Comprobar las dimensiones del procesamiento nuevo

erpMatrices = { ...
    ERP_CON_MMN; ...
    ERP_PEP_MMN; ...
    ERP_CON_CNV_PINV; ...
    ERP_PEP_CNV_PINV; ...
    ERP_CON_PINV; ...
    ERP_PEP_PINV};

erpNames = { ...
    'ERPtotal_CON_MMN'; ...
    'ERPtotal_PEP_MMN'; ...
    'ERPtotal_CON_CNV_PINV'; ...
    'ERPtotal_PEP_CNV_PINV'; ...
    'ERPtotal_CON_PINV_preS4BL'; ...
    'ERPtotal_PEP_PINV_preS4BL'};

for matrixIndex = 1:numel(erpMatrices)

    currentMatrix = erpMatrices{matrixIndex};
    currentName = erpNames{matrixIndex};

    if ndims(currentMatrix) ~= 4
        error('%s debe tener cuatro dimensiones.', currentName);
    end

    if size(currentMatrix, 1) ~= 16
        error('%s no contiene los 16 canales esperados.', currentName);
    end

    if size(currentMatrix, 3) ~= 6
        error('%s no contiene los seis bins esperados.', currentName);
    end

    if size(currentMatrix, 4) < 2
        error('%s contiene menos de dos sujetos.', currentName);
    end
end

clear currentMatrix currentName

if size(ERP_CON_MMN, 2) ~= 350 || ...
        size(ERP_PEP_MMN, 2) ~= 350
    error(['Las matrices MMN deben contener 350 muestras ' ...
        '(-50 a 299 ms respecto a S4).']);
end

if size(ERP_CON_CNV_PINV, 2) ~= 1999 || ...
        size(ERP_PEP_CNV_PINV, 2) ~= 1999 || ...
        size(ERP_CON_PINV, 2) ~= 1999 || ...
        size(ERP_PEP_PINV, 2) ~= 1999
    error(['Las matrices CNV/PINV deben contener 1999 muestras ' ...
        '(-1000 a 998 ms respecto a S4).']);
end

% Recuperar los nombres de los sujetos

if isfield(CON_MMN_DATA, 'subject_names')
    CON_MMN_subject_names = ...
        string(CON_MMN_DATA.subject_names(:));
else
    CON_MMN_subject_names = "CON_" + ...
        compose('%03d', (1:size(ERP_CON_MMN, 4)).');
end

if isfield(PEP_MMN_DATA, 'subject_names')
    PEP_MMN_subject_names = ...
        string(PEP_MMN_DATA.subject_names(:));
else
    PEP_MMN_subject_names = "PEP_" + ...
        compose('%03d', (1:size(ERP_PEP_MMN, 4)).');
end

if isfield(CON_CNV_PINV_DATA, 'subject_names')
    CON_CNV_PINV_subject_names = ...
        string(CON_CNV_PINV_DATA.subject_names(:));
else
    CON_CNV_PINV_subject_names = "CON_" + ...
        compose('%03d', (1:size(ERP_CON_CNV_PINV, 4)).');
end

if isfield(PEP_CNV_PINV_DATA, 'subject_names')
    PEP_CNV_PINV_subject_names = ...
        string(PEP_CNV_PINV_DATA.subject_names(:));
else
    PEP_CNV_PINV_subject_names = "PEP_" + ...
        compose('%03d', (1:size(ERP_PEP_CNV_PINV, 4)).');
end

if numel(CON_MMN_subject_names) ~= size(ERP_CON_MMN, 4)
    error('subject_names no coincide con los controles MMN.');
end

if numel(PEP_MMN_subject_names) ~= size(ERP_PEP_MMN, 4)
    error('subject_names no coincide con los pacientes MMN.');
end

if numel(CON_CNV_PINV_subject_names) ~= ...
        size(ERP_CON_CNV_PINV, 4)
    error('subject_names no coincide con los controles CNV/PINV.');
end

if numel(PEP_CNV_PINV_subject_names) ~= ...
        size(ERP_PEP_CNV_PINV, 4)
    error('subject_names no coincide con los pacientes CNV/PINV.');
end

% Canales representados individualmente

channelIndices = [3 4 5 9 10 6 7];

channelLabels = { ...
    'Fz', ...
    'FCz', ...
    'Cz', ...
    'FC3', ...
    'FC4', ...
    'CPz', ...
    'Pz'};

if numel(channelIndices) ~= numel(channelLabels)
    error('El número de canales y etiquetas no coincide.');
end

% Bins y pesos nominales del paradigma

standardBins = [1 3 5 6];
standardWeights = reshape([150 150 25 25], 1, 1, 4, 1);

deviantBins = [2 4];
deviantWeights = reshape([25 25], 1, 1, 2, 1);

allBins = 1:6;
allWeights = reshape([150 25 150 25 25 25], 1, 1, 6, 1);

% Colores

controlColor = [0 0.4470 0.7410];
patientColor = [0.75 0.25 0.05];
standardColor = [0.9290 0.6940 0.1250];
deviantColor = [0.4660 0.6740 0.1880];

% Ejes temporales reales

samplingRateHz = 1000;
samplingIntervalMs = 1000 / samplingRateHz;
s4AfterS1_ms = 900;

timeMmnS4 = ...
    -50 + (0:(size(ERP_CON_MMN, 2) - 1)) * samplingIntervalMs;

timeCnvPinvS4 = ...
    -940 + (0:(size(ERP_CON_CNV_PINV, 2) - 1)) * ...
    samplingIntervalMs;

timeCnvPinvS1 = timeCnvPinvS4 + s4AfterS1_ms;

if timeMmnS4(1) ~= -50 || timeMmnS4(end) ~= 299
    error('El eje MMN no coincide con -50 a 299 ms.');
end

if timeCnvPinvS4(1) ~= -1000 || timeCnvPinvS4(end) ~= 998
    error('El eje CNV/PINV no coincide con -1000 a 998 ms desde S4.');
end

% Recortes empleados únicamente para la representación
% Se conservan los 100 ms anteriores al primer estímulo representado

mmnPlotMask = timeMmnS4 >= -50;
cnvPlotMask = timeCnvPinvS1 >= -100 & timeCnvPinvS1 <= 900;
pinvPlotMask = timeCnvPinvS4 >= -100;
fullSequencePlotMask = ...
    timeCnvPinvS1 >= -100 & timeCnvPinvS4 <= 998;

timeMMN = timeMmnS4(mmnPlotMask);
timeCNV = timeCnvPinvS1(cnvPlotMask);
timePINV = timeCnvPinvS4(pinvPlotMask);
timeFullSequence = timeCnvPinvS1(fullSequencePlotMask);

% Conservar los nombres completos antes del bucle por canal

CON_MMN_subject_names_all = CON_MMN_subject_names;
PEP_MMN_subject_names_all = PEP_MMN_subject_names;

CON_CNV_PINV_subject_names_all = ...
    CON_CNV_PINV_subject_names;

PEP_CNV_PINV_subject_names_all = ...
    PEP_CNV_PINV_subject_names;

% Procesar cada canal por separado

if ~exist(figurePath, 'dir')
    mkdir(figurePath);
end

if ~exist(pngFigurePath, 'dir')
    mkdir(pngFigurePath);
end

if ~exist(figFigurePath, 'dir')
    mkdir(figFigurePath);
end

if ~exist(plotDataPath, 'dir')
    mkdir(plotDataPath);
end

for channelCounter = 1:numel(channelIndices)

    currentChannel = channelIndices(channelCounter);
    currentLabel = channelLabels{channelCounter};

    channelPngPath = fullfile(pngFigurePath, currentLabel);
    channelFigPath = fullfile(figFigurePath, currentLabel);

    if ~exist(channelPngPath, 'dir')
        mkdir(channelPngPath);
    end

    if ~exist(channelFigPath, 'dir')
        mkdir(channelFigPath);
    end

    CON_MMN_subject_names = CON_MMN_subject_names_all;
    PEP_MMN_subject_names = PEP_MMN_subject_names_all;

    CON_CNV_PINV_subject_names = ...
        CON_CNV_PINV_subject_names_all;

    PEP_CNV_PINV_subject_names = ...
        PEP_CNV_PINV_subject_names_all;

    fprintf('\nProcesando electrodo %s, canal %d.\n', ...
        currentLabel, currentChannel);

    % Seleccionar el canal

    ERP_CON_MMN_current = ...
        ERP_CON_MMN(currentChannel, :, :, :);

    ERP_PEP_MMN_current = ...
        ERP_PEP_MMN(currentChannel, :, :, :);

    ERP_CON_LONG_current = ...
        ERP_CON_CNV_PINV(currentChannel, :, :, :);

    ERP_PEP_LONG_current = ...
        ERP_PEP_CNV_PINV(currentChannel, :, :, :);

    ERP_CON_PINV_current = ...
        ERP_CON_PINV(currentChannel, :, :, :);

    ERP_PEP_PINV_current = ...
        ERP_PEP_PINV(currentChannel, :, :, :);

    % Preparar MMN de controles

    temporaryData = sum( ...
        ERP_CON_MMN_current(1, :, standardBins, :) .* ...
        standardWeights, ...
        3) ./ sum(standardWeights, 3);

    CON_std_MMN = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_CON_MMN_current(1, :, deviantBins, :) .* ...
        deviantWeights, ...
        3) ./ sum(deviantWeights, 3);

    CON_dev_MMN = squeeze(temporaryData).';
    CON_MMN = CON_dev_MMN - CON_std_MMN;

    % Preparar MMN de pacientes

    temporaryData = sum( ...
        ERP_PEP_MMN_current(1, :, standardBins, :) .* ...
        standardWeights, ...
        3) ./ sum(standardWeights, 3);

    PEP_std_MMN = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_PEP_MMN_current(1, :, deviantBins, :) .* ...
        deviantWeights, ...
        3) ./ sum(deviantWeights, 3);

    PEP_dev_MMN = squeeze(temporaryData).';
    PEP_MMN = PEP_dev_MMN - PEP_std_MMN;

    % Preparar CNV y secuencia completa de controles

    temporaryData = sum( ...
        ERP_CON_LONG_current(1, :, standardBins, :) .* ...
        standardWeights, ...
        3) ./ sum(standardWeights, 3);

    CON_LONG_STD = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_CON_LONG_current(1, :, deviantBins, :) .* ...
        deviantWeights, ...
        3) ./ sum(deviantWeights, 3);

    CON_LONG_DEV = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_CON_LONG_current(1, :, allBins, :) .* ...
        allWeights, ...
        3) ./ sum(allWeights, 3);

    CON_LONG_ALL = squeeze(temporaryData).';

    % Preparar CNV y secuencia completa de pacientes

    temporaryData = sum( ...
        ERP_PEP_LONG_current(1, :, standardBins, :) .* ...
        standardWeights, ...
        3) ./ sum(standardWeights, 3);

    PEP_LONG_STD = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_PEP_LONG_current(1, :, deviantBins, :) .* ...
        deviantWeights, ...
        3) ./ sum(deviantWeights, 3);

    PEP_LONG_DEV = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_PEP_LONG_current(1, :, allBins, :) .* ...
        allWeights, ...
        3) ./ sum(allWeights, 3);

    PEP_LONG_ALL = squeeze(temporaryData).';

    % Preparar PINV principal DEV-STD con linea base pre-S4

    temporaryData = sum( ...
        ERP_CON_PINV_current(1, :, standardBins, :) .* ...
        standardWeights, ...
        3) ./ sum(standardWeights, 3);
    CON_PINV_STD = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_CON_PINV_current(1, :, deviantBins, :) .* ...
        deviantWeights, ...
        3) ./ sum(deviantWeights, 3);
    CON_PINV_DEV = squeeze(temporaryData).';
    CON_PINV_DIFF = ...
        CON_PINV_DEV - CON_PINV_STD;

    temporaryData = sum( ...
        ERP_PEP_PINV_current(1, :, standardBins, :) .* ...
        standardWeights, ...
        3) ./ sum(standardWeights, 3);
    PEP_PINV_STD = squeeze(temporaryData).';

    temporaryData = sum( ...
        ERP_PEP_PINV_current(1, :, deviantBins, :) .* ...
        deviantWeights, ...
        3) ./ sum(deviantWeights, 3);
    PEP_PINV_DEV = squeeze(temporaryData).';
    PEP_PINV_DIFF = ...
        PEP_PINV_DEV - PEP_PINV_STD;

    clear temporaryData

    % Excluir únicamente filas con valores no válidos

    validConMmn = ...
        all(isfinite(CON_std_MMN), 2) & ...
        all(isfinite(CON_dev_MMN), 2) & ...
        all(isfinite(CON_MMN), 2);

    validPepMmn = ...
        all(isfinite(PEP_std_MMN), 2) & ...
        all(isfinite(PEP_dev_MMN), 2) & ...
        all(isfinite(PEP_MMN), 2);

    validConLong = ...
        all(isfinite(CON_LONG_STD), 2) & ...
        all(isfinite(CON_LONG_DEV), 2) & ...
        all(isfinite(CON_LONG_ALL), 2) & ...
        all(isfinite(CON_PINV_DIFF), 2);

    validPepLong = ...
        all(isfinite(PEP_LONG_STD), 2) & ...
        all(isfinite(PEP_LONG_DEV), 2) & ...
        all(isfinite(PEP_LONG_ALL), 2) & ...
        all(isfinite(PEP_PINV_DIFF), 2);

    CON_std_MMN = CON_std_MMN(validConMmn, :);
    CON_dev_MMN = CON_dev_MMN(validConMmn, :);
    CON_MMN = CON_MMN(validConMmn, :);
    CON_MMN_subject_names = ...
        CON_MMN_subject_names(validConMmn);

    PEP_std_MMN = PEP_std_MMN(validPepMmn, :);
    PEP_dev_MMN = PEP_dev_MMN(validPepMmn, :);
    PEP_MMN = PEP_MMN(validPepMmn, :);
    PEP_MMN_subject_names = ...
        PEP_MMN_subject_names(validPepMmn);

    CON_LONG_STD = CON_LONG_STD(validConLong, :);
    CON_LONG_DEV = CON_LONG_DEV(validConLong, :);
    CON_LONG_ALL = CON_LONG_ALL(validConLong, :);
    CON_PINV_STD = CON_PINV_STD(validConLong, :);
    CON_PINV_DEV = CON_PINV_DEV(validConLong, :);
    CON_PINV_DIFF = CON_PINV_DIFF(validConLong, :);
    CON_CNV_PINV_subject_names = ...
        CON_CNV_PINV_subject_names(validConLong);

    PEP_LONG_STD = PEP_LONG_STD(validPepLong, :);
    PEP_LONG_DEV = PEP_LONG_DEV(validPepLong, :);
    PEP_LONG_ALL = PEP_LONG_ALL(validPepLong, :);
    PEP_PINV_STD = PEP_PINV_STD(validPepLong, :);
    PEP_PINV_DEV = PEP_PINV_DEV(validPepLong, :);
    PEP_PINV_DIFF = PEP_PINV_DIFF(validPepLong, :);
    PEP_CNV_PINV_subject_names = ...
        PEP_CNV_PINV_subject_names(validPepLong);

    fprintf('Sujetos válidos CON MMN: %d\n', sum(validConMmn));
    fprintf('Sujetos válidos FEP MMN: %d\n', sum(validPepMmn));
    fprintf('Sujetos válidos CON CNV/PINV: %d\n', sum(validConLong));
    fprintf('Sujetos válidos FEP CNV/PINV: %d\n', sum(validPepLong));

    % Guardar las matrices preparadas de cada canal

    save(fullfile(plotDataPath, ...
        ['CON_ERPs_MMN_' currentLabel '_hpf_0p05Hz.mat']), ...
        'CON_std_MMN', ...
        'CON_dev_MMN', ...
        'CON_MMN', ...
        'timeMmnS4', ...
        'CON_MMN_subject_names', ...
        'validConMmn');

    save(fullfile(plotDataPath, ...
        ['PEP_ERPs_MMN_' currentLabel '_hpf_0p05Hz.mat']), ...
        'PEP_std_MMN', ...
        'PEP_dev_MMN', ...
        'PEP_MMN', ...
        'timeMmnS4', ...
        'PEP_MMN_subject_names', ...
        'validPepMmn');

    save(fullfile(plotDataPath, ...
        ['CON_ERPs_CNV_PINV_' currentLabel '_hpf_0p05Hz.mat']), ...
        'CON_LONG_STD', ...
        'CON_LONG_DEV', ...
        'CON_LONG_ALL', ...
        'CON_PINV_DIFF', ...
        'pinvBaselineMsRelativeToS4', ...
        'timeCnvPinvS4', ...
        'timeCnvPinvS1', ...
        'CON_CNV_PINV_subject_names', ...
        'validConLong');

    save(fullfile(plotDataPath, ...
        ['PEP_ERPs_CNV_PINV_' currentLabel '_hpf_0p05Hz.mat']), ...
        'PEP_LONG_STD', ...
        'PEP_LONG_DEV', ...
        'PEP_LONG_ALL', ...
        'PEP_PINV_DIFF', ...
        'pinvBaselineMsRelativeToS4', ...
        'timeCnvPinvS4', ...
        'timeCnvPinvS1', ...
        'PEP_CNV_PINV_subject_names', ...
        'validPepLong');

    % Recortar los datos únicamente para las figuras

    CON_std_MMN_plot = CON_std_MMN(:, mmnPlotMask);
    CON_dev_MMN_plot = CON_dev_MMN(:, mmnPlotMask);
    CON_MMN_plot = CON_MMN(:, mmnPlotMask);

    PEP_std_MMN_plot = PEP_std_MMN(:, mmnPlotMask);
    PEP_dev_MMN_plot = PEP_dev_MMN(:, mmnPlotMask);
    PEP_MMN_plot = PEP_MMN(:, mmnPlotMask);

    CON_CNV_plot = CON_LONG_ALL(:, cnvPlotMask);
    PEP_CNV_plot = PEP_LONG_ALL(:, cnvPlotMask);

    % Unica medida PINV representada: DEV-STD con linea base pre-S4.
    CON_PINV_DIFF_plot = CON_PINV_DIFF(:, pinvPlotMask);
    PEP_PINV_DIFF_plot = PEP_PINV_DIFF(:, pinvPlotMask);

    % Época larga completa desde pre-S1 hasta 998 ms post-S4

    CON_FULL_STD_plot = CON_LONG_STD(:, fullSequencePlotMask);
    CON_FULL_DEV_plot = CON_LONG_DEV(:, fullSequencePlotMask);

    PEP_FULL_STD_plot = PEP_LONG_STD(:, fullSequencePlotMask);
    PEP_FULL_DEV_plot = PEP_LONG_DEV(:, fullSequencePlotMask);

    % En la muestra total cada participante contribuye con el mismo peso

    TOTAL_FULL_STD_plot = [ ...
        PEP_FULL_STD_plot; ...
        CON_FULL_STD_plot];

    TOTAL_FULL_DEV_plot = [ ...
        PEP_FULL_DEV_plot; ...
        CON_FULL_DEV_plot];

    % Especificaciones de todas las figuras
    % La última columna determina el formato del eje temporal

    plotSpecifications = { ...
        CON_std_MMN_plot, standardColor, 'STD', ...
        CON_dev_MMN_plot, deviantColor, 'DEV', ...
        timeMMN, 'CONTROLS: MMN', ...
        0, 'CON_STD_DEV_MMN_hpf_0p05Hz', 'MMN'; ...
        PEP_std_MMN_plot, standardColor, 'STD', ...
        PEP_dev_MMN_plot, deviantColor, 'DEV', ...
        timeMMN, 'FEP: MMN', ...
        0, 'PEP_STD_DEV_MMN_hpf_0p05Hz', 'MMN'; ...
        PEP_dev_MMN_plot, patientColor, 'FEP', ...
        CON_dev_MMN_plot, controlColor, 'CONTROL', ...
        timeMMN, 'DEVIANT: MMN', ...
        0, 'DEV_PEP_vs_CON_MMN_hpf_0p05Hz', 'MMN'; ...
        PEP_std_MMN_plot, patientColor, 'FEP', ...
        CON_std_MMN_plot, controlColor, 'CONTROL', ...
        timeMMN, 'STANDARD: MMN', ...
        0, 'STD_PEP_vs_CON_MMN_hpf_0p05Hz', 'MMN'; ...
